/**
 * elcinema.com/en/ homepage scraper (server-only).
 *
 * Parses the live homepage into the sections the replica page renders:
 * promo carousel, cinema movies panel, watch online, TV summary carousel,
 * TV guide grid, elCinema TV videos, "Born Today", lists and box office tables.
 * The homepage and every extra page it pulls (the day's birth-day listings, in
 * both editions) are cached in memory for 10 minutes.
 */
import * as cheerio from "cheerio";
import type { Element } from "domhandler";
import type {
  Bi,
  EcBoxofficeRow,
  EcBornPerson,
  EcBornToday,
  EcHomeData,
  EcListRow,
  EcMovie,
  EcPromo,
  EcTvGuide,
  EcTvLine,
  EcTvSlot,
  EcTvSummaryItem,
  EcVideo,
  EcVod,
  EcWatchOnlineItem,
} from "@/types/home";
import { pickArtwork } from "@/types/media";
import artworkJson from "@/data/artwork.json";

/**
 * First-party artwork already mirrored into `public/images/`, keyed by kind and
 * the elcinema record id in the filename. Generated by
 * `scripts/mirror-artwork.mjs` from the files actually on disk.
 */
const ARTWORK: Record<"people" | "posters" | "brand", Record<string, string>> = artworkJson;

const BASE = "https://elcinema.com";
const HOME_PATH = "/en/";
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";
const CACHE_TTL_MS = 10 * 60 * 1000;

const cache = new Map<string, { data: unknown; expires: number }>();

async function fetchPage(path: string): Promise<string> {
  const key = `page:${path}`;
  const hit = cache.get(key);
  if (hit && hit.expires > Date.now()) return hit.data as string;

  const res = await fetch(`${BASE}${path}`, {
    headers: { "User-Agent": UA, Accept: "text/html" },
    signal: AbortSignal.timeout(20000),
  });
  if (!res.ok) throw new Error(`elcinema request failed [${res.status}] for ${path}`);
  const html = await res.text();
  cache.set(key, { data: html, expires: Date.now() + CACHE_TTL_MS });
  return html;
}

/**
 * URL rules (empty values, the site root some carousels park in `src`,
 * preview-only asset paths, elcinema's own blank placeholders) live once in
 * `media.shared.ts`, so the parser and the UI agree on what "no artwork" means.
 * The helpers below only add the record-id <-> local-file convention.
 */

const PERSON_ID = /\/person\/(\d+)/;
const WORK_ID = /\/work\/(\d+)/;

/** elcinema record id behind a scraped `/person/<id>/` or `/work/<id>/` href. */
const recordId = (href: string | null | undefined, kind: "person" | "work"): string | null =>
  (kind === "person" ? PERSON_ID : WORK_ID).exec(href ?? "")?.[1] ?? null;

/**
 * First-party copy of a record's artwork, when `scripts/mirror-artwork.mjs` has
 * downloaded it into `public/images/`. Local files are served by this app, so a
 * third-party host going down or hotlink protection cannot blank the section;
 * the scraped remote URL stays available as the second source.
 */
function mirroredArtwork(
  kind: "people" | "posters",
  href: string | null | undefined,
): string | null {
  const id = recordId(href, kind === "people" ? "person" : "work");
  return id ? (ARTWORK[kind][id] ?? null) : null;
}

function clean(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

/** "Sunday  1 November 04:15  PM" -> "Sunday 1 November 04:15 PM" */
function cleanAirtime(text: string): string {
  return clean(text);
}

function parseVod($el: cheerio.Cheerio<Element>): EcVod | null {
  const $a = $el.find(".cta-vod-icon a").first();
  if (!$a.length) return null;
  return {
    href: $a.attr("href") || "#",
    img: pickArtwork($a.find("img"), BASE),
    label: clean($a.find("div").first().text()),
  };
}

function parsePromos($: cheerio.CheerioAPI): EcPromo[] {
  const promos: EcPromo[] = [];
  $(".swiper-default .swiper-slide").each((_, el) => {
    const $s = $(el);
    if ($s.hasClass("swiper-slide-duplicate")) return;
    const $a = $s.find(".slick-caption-wrapper > a").first();
    const img = $s.find(".slick-caption-wrapper img").first();
    promos.push({
      href: $a.attr("href") || `${BASE}/en/`,
      img: pickArtwork(img, BASE),
      title: clean($s.find("h5.section-title").text()),
      button: clean($s.find("a.button").first().text()) || "More",
    });
  });
  return promos;
}

function parseMovies($: cheerio.CheerioAPI): EcMovie[] {
  const $panel = $(".boxed-purple")
    .filter((_, el) => clean($(el).find("h2.section-title").text()) === "Cinema Movies In Egypt")
    .first();
  const movies: EcMovie[] = [];
  $panel.find(".swiper-slide").each((_, el) => {
    const $s = $(el);
    const img = pickArtwork($s.find(".thumbnail-wrapper img"), BASE);
    const $title = $s.find("li.title-height a").first();
    if (!$title.length) return;
    movies.push({
      href: $title.attr("href") || "#",
      img,
      title: clean($title.text()),
      bookingHref: $s.find("a.button.orange.minimize").attr("href") || null,
    });
  });
  return movies;
}

function parseWatchOnline($: cheerio.CheerioAPI): EcWatchOnlineItem[] {
  const $h3 = $("h3.section-title")
    .filter((_, el) => clean($(el).text()) === "Watch Online")
    .first();
  if (!$h3.length) return [];
  const $row = $h3.closest(".row");
  const items: EcWatchOnlineItem[] = [];
  $row.find("ul.unstyled").each((_, el) => {
    const $ul = $(el);
    const $grid = $ul.parents("li").eq(1);
    const img = pickArtwork($grid.find(".thumbnail-wrapper img"), BASE);
    const $lis = $ul.children("li");
    items.push({
      href: $lis.eq(0).find("a").attr("href") || "#",
      img,
      title: clean($lis.eq(0).find("a").text()),
      meta: clean($lis.eq(1).text()),
      vod: parseVod($lis.eq(2)),
    });
  });
  return items;
}

function parseTvSummary($: cheerio.CheerioAPI): EcTvSummaryItem[] {
  const items: EcTvSummaryItem[] = [];
  $(".boxed-4 .swiper-slide").each((_, el) => {
    const $s = $(el);
    const img = pickArtwork($s.find(".thumbnail-wrapper img"), BASE);
    const $lis = $s.find("ul.unstyled").first().children("li");
    if (!$lis.length) return;
    const $title = $lis.eq(0).find("a").first();
    const $channel = $lis.filter((__, li) => $(li).find('img[width="35"]').length > 0).first();
    const $channelA = $channel
      .find('a[href*="/tvguide/"]')
      .filter((__, a) => clean($(a).text()).length > 0)
      .first();
    const timeLi = $lis.toArray().find((li) => clean($(li).text()).match(/(AM|PM)/));
    items.push({
      href: $title.attr("href") || "#",
      img,
      title: clean($title.text()),
      channelImg: pickArtwork($channel.find('img[width="35"]'), BASE),
      channelName: clean($channelA.text()),
      channelHref: $channelA.attr("href") || "#",
      airtime: timeLi ? cleanAirtime($(timeLi).text()) : "",
      vod: parseVod($s.find("ul.unstyled").first()),
    });
  });
  return items;
}

function parseSlot($s: cheerio.Cheerio<Element>): EcTvSlot {
  const cls = ($s.attr("class") || "").split(/\s+/);
  const catMatch = cls.find((c) => /^category-\d+$/.test(c));
  const style = $s.attr("style") || "";
  const width = parseFloat(style.match(/width:\s*([\d.]+)%/)?.[1] || "0");
  const left = parseFloat(style.match(/left:\s*([\d.]+)%/)?.[1] || "0");
  const $lis = $s.find("ul li");
  const $titleA = $lis.eq(0).find("a").first();
  return {
    title: $titleA.length ? clean($titleA.text()) : clean($lis.eq(0).text()),
    titleHref: $titleA.length ? $titleA.attr("href") || null : null,
    meta: clean($lis.eq(1).text()),
    time: clean($lis.eq(2).text()),
    width,
    left,
    unclickable: cls.includes("unclickable"),
    category: catMatch ? parseInt(catMatch.replace("category-", ""), 10) : null,
  };
}

export function parseTvGuide($: cheerio.CheerioAPI): EcTvGuide {
  const $tv = $("#tv-content");
  const times = $(".tv-head .timebar", $tv)
    .map((i, el) =>
      i === 0 ? clean($(el).find(".show-for-medium-up").text()) : clean($(el).text()),
    )
    .get();
  const lines: EcTvLine[] = [];
  $(".tv-line", $tv).each((_, el) => {
    const $line = $(el);
    const $channel = $line.find(".channel").first();
    const $name = $channel.find(".hide-for-small-only a").first();
    lines.push({
      channelImg: pickArtwork($channel.find("img"), BASE),
      channelName: clean($name.text()),
      channelHref: $name.attr("href") || "#",
      slots: $line
        .find(".tv-slot")
        .map((__, s) => parseSlot($(s)))
        .get(),
    });
  });
  return { times, lines };
}

function parseVideos($: cheerio.CheerioAPI): EcVideo[] {
  const videos: EcVideo[] = [];
  $("a.video-wrapper").each((_, el) => {
    const $v = $(el);
    videos.push({
      href: $v.attr("href") || "#",
      img: pickArtwork($v.find("img"), BASE),
      title: clean($v.find("span.title").first().text()),
      duration: clean($v.find("span.duration").first().text()).match(/\d{2}:\d{2}/)?.[0] || null,
    });
  });
  return videos;
}

/**
 * "Born Today" (ولد في مثل هذا اليوم) — the homepage rail of people sharing
 * today's date, with the day's listing link.
 *
 * The homepage publishes only a photo and a name per person; the category,
 * nationality, birth year and death date come from the day's listing page and
 * are merged in `getHomePage`, which also supplies the Arabic name.
 */
export function parseBornToday($: cheerio.CheerioAPI): EcBornToday {
  const $title = $("h2.section-title a")
    .filter((_, a) => ($(a).attr("href") || "").includes("/index/person/birth_day/"))
    .first();
  if (!$title.length) return { date: "", dateKey: "", href: "", people: [] };

  const href = $title.attr("href") || "";
  const dateKey = /birth_day\/(\d{2}-\d{2})/.exec(href)?.[1] ?? "";
  // The day label sits in an `<h6>` the parsers lift out of the `<h2>` (a
  // heading cannot nest), so it is read from the section, not from the title.
  const $section = $title.closest("h2").closest(".columns");
  const date = clean($section.find("h6.subheader a").first().text()) || clean($title.text());

  const people: EcBornPerson[] = [];
  $section
    .find("li")
    .filter((_, li) => $(li).find(".thumbnail-wrapper").length > 0)
    .each((_, el) => {
      const $li = $(el);
      const $a = $li.find(".thumbnail-wrapper a").first();
      const link = $a.attr("href") || "";
      const id = recordId(link, "person");
      if (!id) return;
      const name = clean($li.find("ul.unstyled a").first().text()) || clean($a.text());
      people.push({
        id,
        href: link,
        name: { en: name, ar: name },
        img: pickArtwork($li.find(".thumbnail-wrapper img"), BASE),
        localImg: mirroredArtwork("people", link),
        category: null,
        nationality: null,
        birthYear: null,
        deathDate: null,
      });
    });
  return { date, dateKey, href, people };
}

/** One row of the day listing, in the edition that was scraped. */
interface BirthDayRow {
  name: string;
  img: string | null;
  category: string | null;
  nationality: string | null;
  birthYear: string | null;
  deathDate: string | null;
}

/**
 * `/en/index/person/birth_day/<MM-DD>` — or the Arabic edition of the same page
 * — as a person-id keyed table. The listing is a plain `<table>`: order, person
 * (photo + name), nationality, category, birth day/year, death day/year.
 *
 * The page is paginated (25 rows) and this reads only the first one, which is
 * what the merge below uses; a rail person further down the day's list keeps
 * the photo and name the homepage published.
 */
export function parseBirthDayList(html: string): Map<string, BirthDayRow> {
  const $ = cheerio.load(html);
  const rows = new Map<string, BirthDayRow>();
  $("table tr")
    .filter((_, tr) => $(tr).find("td").length >= 6)
    .each((_, tr) => {
      const $tds = $(tr).find("td");
      const id = recordId($tds.eq(1).find("a").first().attr("href"), "person");
      if (!id) return;
      const death = clean($tds.eq(5).text());
      rows.set(id, {
        name: clean($tds.eq(1).find("a").last().text()),
        img: pickArtwork($tds.eq(1).find("img"), BASE),
        nationality: clean($tds.eq(2).text()) || null,
        category: clean($tds.eq(3).text()) || null,
        birthYear: $tds.eq(4).find("a[href*='birth_year/']").first().text().trim() || null,
        deathDate: death || null,
      });
    });
  return rows;
}

/** A bilingual pair from the two editions of one field, falling back across. */
const pairOf = (en: string | null, ar: string | null): Bi | null => {
  const english = en || ar || null;
  const arabic = ar || en || null;
  return english && arabic ? { en: english, ar: arabic } : null;
};

/**
 * Fill the homepage rail with the listing pages' data. Both editions are read:
 * the English one for the professional fields, the Arabic one so the rail is
 * bilingual like the rest of the app. A missing or failing listing leaves the
 * rail exactly as the homepage sent it.
 */
async function enrichBornToday(born: EcBornToday): Promise<EcBornToday> {
  if (!born.dateKey || !born.people.length) return born;
  const [enHtml, arHtml] = await Promise.all([
    fetchPage(`/en/index/person/birth_day/${born.dateKey}`).catch(() => null),
    fetchPage(`/ar/index/person/birth_day/${born.dateKey}`).catch(() => null),
  ]);
  if (!enHtml && !arHtml) return born;
  const en = enHtml ? parseBirthDayList(enHtml) : new Map<string, BirthDayRow>();
  const ar = arHtml ? parseBirthDayList(arHtml) : new Map<string, BirthDayRow>();
  return {
    ...born,
    people: born.people.map((p) => {
      const e = en.get(p.id);
      const a = ar.get(p.id);
      return {
        ...p,
        name: {
          en: e?.name || p.name.en,
          ar: a?.name || p.name.ar,
        },
        // The rail's photo is the 315x420 homepage image; the listing only
        // carries a 75x75 thumb, used when the homepage published a blank one.
        img: p.img ?? e?.img ?? a?.img ?? null,
        category: pairOf(e?.category ?? null, a?.category ?? null),
        nationality: pairOf(e?.nationality ?? null, a?.nationality ?? null),
        birthYear: e?.birthYear ?? a?.birthYear ?? null,
        deathDate: pairOf(e?.deathDate ?? null, a?.deathDate ?? null),
      };
    }),
  };
}

function parseLists($: cheerio.CheerioAPI): EcListRow[] {
  const $h2 = $("h2.section-title")
    .filter((_, el) => clean($(el).find("a").first().text()) === "Lists")
    .first();
  if (!$h2.length) return [];
  const rows: EcListRow[] = [];
  $h2
    .closest(".columns")
    .find("table td a")
    .each((_, a) => {
      rows.push({ href: $(a).attr("href") || "#", title: clean($(a).text()) });
    });
  return rows;
}

function parseBoxoffice($: cheerio.CheerioAPI): { date: string; rows: EcBoxofficeRow[] } {
  const $h2 = $("h2.section-title")
    .filter((_, el) => clean($(el).find("a").first().text()) === "Boxoffice")
    .first();
  if (!$h2.length) return { date: "", rows: [] };
  const $col = $h2.closest(".columns");
  const date = clean($col.find("h6 a").first().text());
  const rows: EcBoxofficeRow[] = [];
  $col.find("table tbody tr").each((_, tr) => {
    const $tds = $(tr).find("td");
    if ($tds.length < 2) return;
    const $title = $tds
      .eq(0)
      .find("a")
      .filter(
        (__, a) => ($(a).attr("href") || "").includes("/work/") && clean($(a).text()).length > 0,
      )
      .first();
    rows.push({
      href: $title.attr("href") || "#",
      title: clean($title.text()),
      img: pickArtwork($tds.eq(0).find("img"), BASE),
      revenue: clean($tds.eq(1).text()),
    });
  });
  return { date, rows };
}

export function parseHomePage(html: string): EcHomeData {
  const $ = cheerio.load(html);
  const boxoffice = parseBoxoffice($);
  return {
    promos: parsePromos($),
    movies: parseMovies($),
    watchOnline: parseWatchOnline($),
    tvSummary: parseTvSummary($),
    tvGuide: parseTvGuide($),
    videos: parseVideos($),
    bornToday: parseBornToday($),
    lists: parseLists($),
    boxofficeDate: boxoffice.date,
    boxoffice: boxoffice.rows,
  };
}

export async function getHomePage(): Promise<EcHomeData> {
  const key = `home:${HOME_PATH}`;
  const hit = cache.get(key);
  if (hit && hit.expires > Date.now()) return hit.data as EcHomeData;
  const data = parseHomePage(await fetchPage(HOME_PATH));
  // Enrichment reads two more pages, so it degrades to the bare rail instead
  // of failing the whole homepage when the listing is unreachable.
  data.bornToday = await enrichBornToday(data.bornToday);
  cache.set(key, { data, expires: Date.now() + CACHE_TTL_MS });
  return data;
}
